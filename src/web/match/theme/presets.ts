export type BaseRole = (typeof baseRoles)[number];
export type DerivedRole = keyof typeof derivedRoles;
export type ThemeRole = BaseRole | DerivedRole;
export const themeRoles = [...baseRoles, ...(Object.keys(derivedRoles) as DerivedRole[])];
